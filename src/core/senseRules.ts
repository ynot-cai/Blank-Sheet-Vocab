/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  ★★★ 资料整理规范（AI 录入 + 手动录入 + 预设词库 都必须遵守） ★★★
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 这是全项目**唯一**的「一个词该怎么整理」的权威定义。
 * 改规则**只改这个文件**：`services/ai.ts` 的 AI 提示词会引用下面的
 * `SENSE_RULES_FOR_AI`，`normalizeAliases` 会被所有写入路径调用。
 * 三个地方（提示词 / 代码兜底 / 文档）如果各写一份，迟早会互相矛盾。
 *
 * ⚠️ 与项目铁律 `开发必读/逻辑与交互要求.md` §4.1 的关系：
 *   §4.1 是**必含片段**（短摘要，会被自检逐字比对），本文件是**详细规范**（五步细则）。
 *   两者由 `services/ai.ts` 的 `PARSE_SYSTEM_PROMPT` 一起拼进提示词，**不许互相矛盾**。
 *
 * ── 五步流程（版本 0.0.6 起）──────────────────────────────────────────────
 *
 *   第 1 步  补全这个词或短语的**全部**中文意思与音标（一个都不许漏）
 *   第 2 步  把中文意思**分类成几个义项**（一个义项 = 一个独立核心含义；相近的归一类）
 *   第 3 步  在每一类里**挑一个「代表」**（最常用、最直白的那个说法）
 *   第 4 步  把同一类里其余的**近义词逐个分隔开**放好（一个近义词一项，不许打包）
 *   第 5 步  **每个义项**配一条例句，优先引用牛津词典；找不到就填「暂无」
 *
 *   ★ 词性怎么处理（版本 0.0.6 按用户要求**反转**，注意与旧版相反）：
 *       **不同词性一律视为不同含义 → 必须拆成不同义项**，并在代表词里保留词性前缀。
 *     旧版规则是「多词性时判断是否同源，同源则跨词性合并」——
 *     那条已作废删除。两条规则正好相反，不能并存，留着必然互相矛盾。
 *
 * ── 数据落地形态 ──────────────────────────────────────────────────────────
 *
 *   义项 = `{ text: 代表词, aliases: [近义词…], example: 例句 }`
 *
 *   - `text`    第 3 步选出的**代表**。可以带词性前缀（`v. 跑`），也可以不带（`跑`）。
 *   - `aliases` 第 4 步拆好的近义词。**每一项只能是一个中文说法**。
 *   - `example` 第 5 步的例句，**义项级**（一个词有 3 个义项就有 3 条）。
 *     找不到时原样写「暂无」，不要编造、不要留空。
 *
 * ── 范例（run）────────────────────────────────────────────────────────────
 *
 *   词表原文：
 *     run  v. 跑，经验  n. 跑步，短途跑步
 *
 *   正确整理（3 个义项）：
 *     义项①  text="v. 跑"     aliases=[]            example="He runs every morning."
 *     义项②  text="v. 经验"   aliases=[]            example="暂无"
 *     义项③  text="n. 跑步"   aliases=["短途跑步"]   example="I went for a run."
 *
 *   为什么①里的动词性「跑」**不能**把名词性的「跑步」并进来：
 *     版本 0.0.6 起，**词性不同就是不同含义**，必须各成一项。
 *     （旧版会把它们合并——那条规则已作废，见上面的说明。）
 *
 * ── 两条硬约束（会被代码强制执行，不只是提示词里的要求）────────────────────
 *
 *   ★ 约束 1：一个近义词里**只能有一个中文说法**。
 *     反例：aliases:["跑步，奔跑"] —— 判分时会被归一化成「跑步奔跑」，
 *     用户答「跑步」或「奔跑」**都判错**（因为整串不相等）。
 *     正确：aliases:["跑步","奔跑"]。
 *     这里两个词都是中文；**混英文也不行**（aliases:["跑/run"] 同样会判错）。
 *
 *   ★ 约束 2：白纸上「点单词 → 显示中文」**只显示每个义项的代表词**（text），
 *     近义词一律不显示。所以代表词必须挑得能独立代表整个义项，
 *     不能挑一个「离开近义词就看不懂」的说法。
 *     实现见 `core/model.ts` 的 `formatSensesBrief()`（它只读 `s.text`）。
 *
 * ── 为什么要写成这么细 ────────────────────────────────────────────────────
 * 这些不是洁癖，每一条都对应一个真实的坏结果：
 *   · 义项不拆开     → 代表词是一长串，用户答对一半也算错
 *   · 近义词打包     → 归一化后整串不等，**答哪个都判错**（上面已实测）
 *   · 不同词性不拆开 → 一个义项里混着名词义和动词义，复习时答哪个都别扭
 *   · 例句缺失/编造  → 用户看不到真实用法，还可能学到错句子
 *
 * ── 严谨度要求的放宽（用户 2026-10-15 明确）────────────────────────────────
 *   用户说：「以后『输入中文意思』的判分将交给 AI 完成，因此义项划分的严谨程度要求可以降低。」
 *   所以第 2/3 步的边界情况（两可的归类）**不再要求开发者纠结**，交给 AI 判分兜底。
 *   但上面两条硬约束仍然保留——它们防的是**数据形态坏掉**（判分永远对不上），
 *   与「归类严不严谨」不是一回事。
 */

/** 近义词之间的分隔符（写提示词、清洗历史数据都用这一份） */
export const ALIAS_SEPARATORS = /[，,、;；/|·]+/;

/** 义项文本里不允许出现的内部分隔符（出现了说明作者把多个含义打包了） */
export const SENSE_TEXT_FORBIDDEN_SEPARATORS = /[，,、;；]/;

/** 例句找不到时的占位文案（用户指定：原样写「暂无」） */
export const EXAMPLE_NOT_FOUND = '暂无';

/**
 * 提供给 AI 的规则正文（`services/ai.ts` 直接拼进 system prompt）。
 *
 * ★ 单独抽成常量而不是写在提示词模板里：这样自检可以断言
 *   「提示词里确实包含这些规则」，避免以后有人改提示词时把规则删掉。
 */
export const SENSE_RULES_FOR_AI = `资料整理规范（五步，必须严格执行）：

第 1 步 · 补全中文意思与音标
  补全这个词或短语的**全部**中文意思与音标，一个都不许漏。
  原文给了中文就照它整理，没给或给得不全就由你补全。

第 2 步 · 分类成义项
  把这些中文意思分类成一个或多个义项。一个义项 = 一个独立的核心含义。
  含义相近的归为一类；绝不允许把多个不相干的含义塞进同一个义项。

第 3 步 · 挑代表
  每个义项挑**一个**最常用、最直白的说法作为代表词，写进 text。
  代表词必须能独立看懂——因为界面上「点单词显示中文」**只显示代表词**，不显示近义词。

第 4 步 · 近义词逐个分隔
  同一个义项内的其余说法作为近义词，**一个说法一项**写进 aliases 数组。
  ★ 严禁把多个说法打包成一项：aliases:["跑步，奔跑"] 是**错的**，
    必须是 aliases:["跑步","奔跑"]。
    打包的后果很严重：判分时整串比对，用户答「跑步」或「奔跑」都会被判错。
  ★ 每个近义词只能是**一个纯中文说法**，不许夹英文、不许带标点、不许带解释。

第 5 步 · 每个义项配例句
  给**每一个义项**写一条例句，放进该义项的 example 字段。
  · 优先引用**牛津词典**里该义项对应的例句（这是用户明确要求的来源）。
  · 确实找不到合适的例句，就**原样填「${EXAMPLE_NOT_FOUND}」**——不要编造，
    不要留空，不要写别的占位话。
  · 例句要短、要能体现该义项本身的用法（不是体现这个词的别的义项）。
  ⚠️ 例句是**义项级**的，不是单词级的：一个词有 3 个义项就有 3 条例句。

★ 词性怎么处理（**这条与旧版规则相反，务必按新版执行**）
  **不同词性一律视为不同含义，必须拆成不同义项**，并在代表词里保留词性前缀。

  范例（run）：原文「run  v. 跑，经验  n. 跑步，短途跑步」
    正确答案是 3 个义项：
      {"text":"v. 跑","aliases":[],"example":"He runs every morning."}
      {"text":"v. 经验","aliases":[],"example":"${EXAMPLE_NOT_FOUND}"}
      {"text":"n. 跑步","aliases":["短途跑步"],"example":"I went for a run."}
    注意：名词性的「跑步」**不能**并进动词性的「跑」——词性不同就是不同含义。

  反例（bear）：原文「bear  n. 熊  v. 忍受」
    「熊」和「忍受」词性不同、含义也不相干 → 必须拆成：
      {"text":"n. 熊","aliases":[],"example":"..."}
      {"text":"v. 忍受","aliases":[],"example":"..."}
    绝对不许把它们并成一个义项。

补充：义项文本里不要出现顿号/逗号（「n. 量纲、维度」是错的），
      那说明你把多个含义打包了，应该拆成多个义项。`;

/** 一个可以安全展示/判分的义项 */
export interface SenseLike {
  text: string;
  aliases: string[];
  /** 义项级例句；找不到时是 `暂无`。旧数据可能没有这个字段。 */
  example?: string;
}

/**
 * 归一化近义词列表：把打包的说法拆开、去空、去重。
 *
 * ★ 这个函数是「约束 1」的执行点，所有写入路径都必须过一遍：
 *   AI 解析结果、规则解析结果、用户在卡片里手动编辑、预设词库导入。
 *   不过这一遍的话，模型偶尔返回 `["跑步，奔跑"]` 就会让判分永远失败，
 *   而且**界面上完全看不出来**——这是最难查的一类问题。
 *
 * @param aliases 原始近义词列表（可能含打包项 / 空串 / 重复）
 */
export function normalizeAliases(aliases: readonly string[]): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const raw of aliases) {
    if (typeof raw !== 'string') continue;
    for (const piece of raw.split(ALIAS_SEPARATORS)) {
      const item = piece.trim();
      if (item === '') continue;
      // 去重按「原样」比：不做归一化去重，避免把「跑步」和「跑步。」这类误判成同一个
      if (seen.has(item)) continue;
      seen.add(item);
      out.push(item);
    }
  }
  return out;
}

/**
 * 归一化一个义项的例句。
 *
 * 规则（用户指定）：找不到就填「暂无」。所以这里把空值统一成 `暂无`，
 * 让「没找到」在数据里是**显式的**，而不是一个看起来像漏填的空串。
 * @param example 原始例句（可能是 undefined / 空白）
 */
export function normalizeSenseExample(example: unknown): string {
  if (typeof example !== 'string') return EXAMPLE_NOT_FOUND;
  const t = example.trim();
  return t === '' ? EXAMPLE_NOT_FOUND : t;
}

/**
 * 检查一个义项是否符合规范，返回问题清单（空数组 = 合规）。
 *
 * 只报**真会导致功能坏掉**的问题，不做风格挑剔：
 *   · 代表词为空           → 界面上会显示空义项
 *   · 代表词里含分隔符     → 说明多个含义被打包了
 *   · 近义词里含分隔符     → 判分会永久失败（这就是约束 1 要防的）
 *   · 近义词与代表词重复   → 冗余
 *
 * ⚠️ 版本 0.0.6：**例句为空不再算问题** —— 用户明确要求找不到就填「暂无」，
 *   `normalizeSenseExample()` 已经把空值统一成「暂无」，所以这里不必再报。
 * @param sense 待检查的义项
 */
export function validateSenseShape(sense: SenseLike): string[] {
  const problems: string[] = [];
  const text = sense.text.trim();
  if (text === '') problems.push('代表词为空');
  else if (SENSE_TEXT_FORBIDDEN_SEPARATORS.test(text)) {
    problems.push(`代表词里含顿号/逗号（「${text}」），说明多个含义被塞进了一个义项`);
  }
  for (const alias of sense.aliases) {
    if (ALIAS_SEPARATORS.test(alias)) {
      problems.push(`近义词「${alias}」里含分隔符，应该拆成多个（否则判分永远对不上）`);
    }
    if (alias.trim() === '') problems.push('近义词里有空串');
  }
  return problems;
}
