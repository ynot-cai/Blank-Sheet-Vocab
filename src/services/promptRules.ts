/**
 * 录入解析提示词必含片段（AI_RULES.md 第 4.1 节，**原文**）。
 * 用于：一期 `services/ai.ts` 的 `PARSE_SYSTEM_PROMPT`、
 *       二期 `services/kcPrompts.ts` 的 `KC_IMPORT_SYSTEM_PROMPT`。
 */
export const MANDATORY_IMPORT_RULES = `【义项处理规则 - 必须严格遵守】
1. 含义相近的中文意思合并为一个义项，选一个最常用的作为代表义项，
   其余作为近义词(aliases)。例：「高兴/快乐/愉快」→ 一个义项，
   代表「高兴」，aliases = ["快乐","愉快"]
2. 确实不同的意思必须拆成不同义项。例：「bank → 银行 / 河岸」是两个义项
3. 音标、例句缺失则补全
4. 只为多义词/多词性单词建立多个义项；单义词只建一个
5. 输出严格 JSON`;

