/**
 * 录入解析提示词必含片段（规则文件第 4.1 节，**原文**）。
 * ★ 版本 0.0.6 按用户要求改过：新增「不同词性视为不同含义」与「每个义项配牛津例句」，
 *   原来的「多词性判断同源、同源可跨词性合并」**已作废删除**（两条规则正好相反）。
 * 用于：`services/ai.ts` 的 `PARSE_SYSTEM_PROMPT`。
 */
export const MANDATORY_IMPORT_RULES = `【义项处理规则 - 必须严格遵守】
1. 补全这个词或短语的中文意思与音标，一个都不许漏
2. 含义相近的中文意思合并为一个义项，选一个最常用的作为代表义项，
   其余作为近义词(aliases)。例：「高兴/快乐/愉快」→ 一个义项，
   代表「高兴」，aliases = ["快乐","愉快"]
3. 不同词性一律视为不同含义，必须拆成不同义项，并在代表义项里保留词性前缀。
   例：「bear」的「n. 熊」与「v. 忍受」是两个义项，不许合并
4. 每个义项都要配一条例句，优先引用牛津词典里的例句；确实找不到就填「暂无」
5. 输出严格 JSON`;

